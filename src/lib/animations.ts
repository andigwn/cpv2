/**
 * Where the wavy edge sits inside the wipe mask tile, in percent.
 *
 * A wipe is a soft wavy edge rather than a hard line: the mask is drawn twice the frame wide
 * with its opaque side running from that edge out to the far edge of the tile. Sliding the tile
 * drags the edge across the frame, and which side is opaque decides which way the frame fills.
 * `hero-wipe-mask.svg` is opaque to the right of the edge (30% into the tile);
 * `hero-wipe-mask-alt.svg`, its mirror generated by `_tools/generate-wipe-mask.mjs`, is opaque
 * to the left (70% in). That mirror is what lets the frame also fill from the left.
 */
export const WIPE_EDGE_IN_TILE = 30;

export type WipeVariant = {
  /** Which side of the wavy edge is opaque, and therefore which way the frame fills. */
  fill: "left" | "right";
  /**
   * The edge's position across the frame at the start and end of the wipe, in percent.
   * Anything outside 0-100 puts the edge off-screen, which is what makes an incoming layer
   * begin fully hidden. The far end is additionally held inside `WIPE_EDGE_WINDOW` — see below
   * for why overshooting there tears the frame rather than just looking slow.
   */
  edge: readonly [number, number];
  /** This hand-over's duration, so consecutive wipes do not share a rhythm either. */
  seconds: number;
  /** Ken Burns direction for the layer this wipe brings in. */
  zoom: "in" | "out";
};

/**
 * The window each end of a wipe has to stay inside, derived from the mask geometry.
 *
 * The tile is twice the frame wide, so sliding it by `p` percent puts the opaque side at a
 * position derived from `p` alone:
 *
 * - `fill: "right"` — opaque runs from the edge (60% into the tile) to the tile's far edge, so
 *   it covers the frame only while `p` is between 60 and 100, i.e. an edge between -40 and 0.
 * - `fill: "left"` — opaque runs from the tile's near edge to the edge (70% in), so it covers
 *   the frame only while `p` is between 0 and 40, i.e. an edge between 100 and 140.
 *
 * Travel past the far end of that window slides the opaque side back *out* of the frame, so the
 * layer stops covering it and the dark base underneath shows through as a growing band on the
 * side the edge has already crossed. That reads as a torn frame, not a wipe. Every edge is
 * therefore clamped into its window, which turns an over-long travel into "slightly slower"
 * instead of a visible gap.
 */
const WIPE_EDGE_WINDOW: Record<
  WipeVariant["fill"],
  { from: [number, number]; to: [number, number] }
> = {
  right: { from: [100, Number.POSITIVE_INFINITY], to: [-40, 0] },
  left: { from: [Number.NEGATIVE_INFINITY, 0], to: [100, 140] },
};

const clamp = (value: number, [low, high]: readonly [number, number]) =>
  Math.min(Math.max(value, low), high);

/** Converts a variant's edge positions into the `mask-position` offsets the component animates. */
export function wipeOffset(fill: WipeVariant["fill"], edge: number): string {
  const edgeInTile = fill === "left" ? 100 - WIPE_EDGE_IN_TILE : WIPE_EDGE_IN_TILE;
  return `${edgeInTile * 2 - edge}%`;
}

/**
 * Hero rotating background timings.
 *
 * The photo change is an Ayana-style mask wipe: the incoming photo mounts on top of
 * the outgoing one and is revealed by a soft wavy edge sweeping across the frame, so the old
 * photo is wiped away without ever cutting or flashing. Every photo also keeps pushing in
 * slowly for as long as it is on screen (Ken Burns), so the frame keeps drifting between wipes.
 */
export const ROTATION = {
  /** How long a single photo stays fully on screen before the next wipe starts. */
  intervalMs: 7000,
  /** Grace period after the wipe before the incoming layer becomes the base, in ms. */
  wipeSettleMs: 240,
  /**
   * Ken Burns drift. Even photos zoom in from 1 to 1.1, odd photos zoom back out
   * from 1.1 to 1, so consecutive photos never repeat the same move. One photo is
   * still drifting when it is swapped out.
   */
  zoom: { from: 1, to: 1.1, seconds: 9 },
  /**
   * Wipe choreography, cycled in order so consecutive hand-overs never repeat. The direction
   * alternates, and each direction appears once at a relaxed speed and once at a different
   * one, so the loop does not read as a single move played forwards and backwards. Each entry
   * also pairs the wipe with a Ken Burns direction, which keeps the two from feeling locked
   * together.
   *
   * Cycled by hand-over counter rather than by slide index, so the rhythm does not depend on
   * how many photos a venue happens to have. Pairing `fill` with `zoom` deliberately avoids a
   * strict period of two: `in/out/out/in` rather than `in/out/in/out`.
   */
  wipes: [
    { fill: "right", edge: [110, -30], seconds: 3.2, zoom: "in" },
    { fill: "left", edge: [-5, 130], seconds: 3.2, zoom: "out" },
    { fill: "right", edge: [128, -18], seconds: 2.4, zoom: "out" },
    { fill: "left", edge: [-22, 126], seconds: 4.2, zoom: "in" },
  ] satisfies readonly WipeVariant[],
} as const;

/** The variants with every edge held inside `WIPE_EDGE_WINDOW`, resolved once at module load. */
const WIPES: readonly WipeVariant[] = ROTATION.wipes.map((variant) => {
  const window = WIPE_EDGE_WINDOW[variant.fill];
  return {
    ...variant,
    edge: [clamp(variant.edge[0], window.from), clamp(variant.edge[1], window.to)],
  };
});

/** The wipe variant for a given hand-over counter. */
export function wipeVariant(handovers: number): WipeVariant {
  return WIPES[handovers % WIPES.length];
}

