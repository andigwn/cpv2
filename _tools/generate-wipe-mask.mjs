/**
 * Development-only helper (NOT part of the app bundle).
 *
 * Derives `public/images/hero-wipe-mask-alt.svg` — the exact horizontal mirror of
 * `hero-wipe-mask.svg`.
 *
 * The original mask's opaque side runs from a wavy edge out past the right edge of its
 * viewBox, which is what makes the hero frame fill right-to-left as the tile slides. Mirroring
 * every x coordinate about the viewBox's vertical axis puts the opaque side on the other side,
 * so the same sliding motion fills left-to-right. Without the mirror, reversing the slide would
 * simply hide the incoming photo instead of revealing it.
 *
 * Re-run after replacing either asset:
 *   node _tools/generate-wipe-mask.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "public", "images", "hero-wipe-mask.svg");
const OUT = path.join(ROOT, "public", "images", "hero-wipe-mask-alt.svg");
const VIEWBOX_WIDTH = 250;

/** Coordinate pairs each path command consumes: M/L take one, C takes three, Z none. */
const ARITY = { M: 1, L: 1, C: 3, Z: 0 };

const round = (value) => Number(value.toFixed(2));

const svg = readFileSync(SRC, "utf8");
const source = svg.match(/ d="([^"]+)"/);
if (!source) throw new Error("no path data found in hero-wipe-mask.svg");

const mirrored = source[1].replace(/([MLCZ])([^MLCZ]*)/gi, (match, command, tail) => {
  if ((ARITY[command.toUpperCase()] ?? 0) === 0) return command;

  const numbers = (tail.match(/-?\d+(?:\.\d+)?/g) ?? []).map(Number);
  const reflected = [];
  for (let i = 0; i + 1 < numbers.length; i += 2) {
    reflected.push(round(VIEWBOX_WIDTH - numbers[i]), round(numbers[i + 1]));
  }
  return `${command} ${reflected.join(" ")}`;
});

writeFileSync(
  OUT,
  `<svg xmlns="http://www.w3.org/2000/svg" width="250" height="625" viewBox="0 0 250 625" preserveAspectRatio="none">
  <!-- GENERATED by _tools/generate-wipe-mask.mjs — the horizontal mirror of
       hero-wipe-mask.svg, so the hero wipe can fill from the left as well as from the right.
       Do not edit by hand. -->
  <defs>
    <filter id="feather" x="-40%" y="-10%" width="180%" height="120%">
      <feGaussianBlur stdDeviation="8" />
    </filter>
  </defs>
  <path fill="#ffffff" filter="url(#feather)" d="${mirrored}" />
</svg>
`,
  "utf8",
);

/** Share of the 25 columns of the tile that the path's points fall in — a mirror check. */
function density(d) {
  const numbers = d.match(/-?\d+(?:\.\d+)?/g).map(Number);
  const columns = new Array(25).fill(0);
  for (let i = 0; i + 1 < numbers.length; i += 2) {
    const column = Math.floor((numbers[i] / VIEWBOX_WIDTH) * 25);
    columns[Math.min(24, Math.max(0, column))]++;
  }
  return columns
    .map((count, i) => `${i * 4}-${i * 4 + 4}%:${count}`)
    .filter((entry) => !entry.endsWith(":0"))
    .join("  ");
}

console.log(`wrote ${path.relative(ROOT, OUT)}`);
console.log(`original: ${density(source[1])}`);
console.log(`mirrored: ${density(mirrored)}`);